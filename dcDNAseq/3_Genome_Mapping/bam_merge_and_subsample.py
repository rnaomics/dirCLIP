############################################################
# Function: Create directory if it does not exist
############################################################
def create_output_folder(directory):

    try:
        if not os.path.exists(directory):
            os.makedirs(directory)

    except OSError:
        print("Error: Creating directory. " + directory)

############################################################
# Function: Merge BAM files
############################################################
def merge_bam_files(
        bam_directories,
        result_directories,
        bam_filename,
        threads):

    for group_idx in range(len(bam_directories)):

        ####################################################
        # Input BAM files
        ####################################################
        bam_directory_group = bam_directories[group_idx]

        bam_files = [
            bam_dir + bam_filename
            for bam_dir in bam_directory_group
        ]

        ####################################################
        # Output BAM file
        ####################################################
        result_directory = result_directories[group_idx]

        merged_bam_file = (
            result_directory +
            bam_filename
        )

        create_output_folder(
            result_directory
        )

        ####################################################
        # Merge BAM files
        ####################################################
        command = (
            "samtools merge -f -@ "
            + str(threads)
            + " "
            + merged_bam_file
            + " "
            + " ".join(bam_files)
        )

        print(command)

        subprocess.call(
            command,
            shell=True
        )

        ####################################################
        # Remove temporary files generated by samtools
        ####################################################
        remove_command = (
            "rm "
            + merged_bam_file
            + ".tmp.*"
        )

        print(remove_command)

        subprocess.call(
            remove_command,
            shell=True
        )

        ####################################################
        # Sort merged BAM
        ####################################################
        command = (
            "samtools sort -@ "
            + str(threads)
            + " -o "
            + merged_bam_file
            + " "
            + merged_bam_file
        )

        print(command)

        subprocess.call(
            command,
            shell=True
        )

############################################################
# Function: Generate BAM subsamples
############################################################

def subsample_bam(
        number_of_subsamples,
        sample_percentage,
        result_directories,
        bam_filename,
        threads):
    """
    Generate multiple BAM subsamples using deterministic random seeds.

    Parameters
    ----------
    number_of_subsamples : int
        Number of subsamples to generate for each BAM file.

    sample_percentage : int or float
        Percentage of reads to keep (must be > 0 and < 100).

    result_directories : list
        List of directories containing the input BAM files.

    bam_filename : str
        BAM filename to subsample.

    threads : int
        Number of CPU threads used for BAM sorting.
    """

    ########################################################
    # Validate sampling percentage
    ########################################################

    if sample_percentage <= 0 or sample_percentage >= 100:
        raise ValueError(
            "sample_percentage must be greater than 0 "
            "and less than 100."
        )

    ########################################################
    # Generate deterministic random seeds
    ########################################################

    sampling_seeds = list(
        range(
            100,
            number_of_subsamples * 100 + 1,
            100
        )
    )

    ########################################################
    # Generate subsamples
    ########################################################

    for result_directory in result_directories:

        for subsample_idx in range(number_of_subsamples):

            ################################################
            # Input and output files
            ################################################

            merged_bam_file = os.path.join(
                result_directory,
                bam_filename
            )

            subsample_directory = os.path.join(
                result_directory,
                f"subsample_{sample_percentage}",
                f"SS{subsample_idx + 1}"
            )

            subsample_bam_file = os.path.join(
                subsample_directory,
                bam_filename
            )

            subsample_bed_file = (
                subsample_bam_file.replace(
                    ".bam",
                    ".bed.gz"
                )
            )

            create_output_folder(
                subsample_directory
            )

            ################################################
            # Samtools sampling fraction
            #
            # Examples:
            #
            # seed=100, percentage=5
            #      -> 100.05
            #
            # seed=100, percentage=70
            #      -> 100.70
            #
            # seed=100, percentage=99
            #      -> 100.99
            ################################################

            sampling_fraction = (
                sampling_seeds[subsample_idx]
                + sample_percentage / 100.0
            )

            ################################################
            # Subsample and sort BAM
            ################################################

            command = (
                "samtools view -s "
                + str(sampling_fraction)
                + " -b "
                + merged_bam_file
                + " | samtools sort -@ "
                + str(threads)
                + " -o "
                + subsample_bam_file
            )

            print(command)

            subprocess.call(
                command,
                shell=True
            )

            ################################################
            # Index subsampled BAM
            ################################################

            command = (
                "samtools index "
                + subsample_bam_file
            )

            print(command)

            subprocess.call(
                command,
                shell=True
            )

            ################################################
            # Convert BAM to BED
            ################################################

            command = (
                "bedtools bamtobed -i "
                + subsample_bam_file
                + " | pigz > "
                + subsample_bed_file
            )

            print(command)

            subprocess.call(
                command,
                shell=True
            )

